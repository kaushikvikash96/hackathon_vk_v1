def gen_afr() -> Iterator[Example]:
    for term in AFR_TERMS:
        pattern = term if any(ch in term for ch in "?|") else rf"\b{term}\b"

        args = {"dataset": "afr", "metric": "count", "pattern": pattern, "group_by": "year_and_month"}
        result = run_tool("query_data", args)
        if not result.ok:
            continue
        v = _values(result)
        if "peak_year" not in v:
            continue
        by_year = result.detail["by_year"]
        by_month = result.detail["by_month"]
        peak_year_count = by_year[str(v["peak_year"])]
        peak_month_count = by_month[v["peak_month"]]
        gold = (
            f"There are {fmt_int(v['match_count'])} matching AFR records in total. Coverage peaked "
            f"in {v['peak_year']} with {fmt_int(peak_year_count)} records, and "
            f"{v['peak_month']} is the peak month with {fmt_int(peak_month_count)}."
        )
        question = RNG.choice([
            f"Using a case-insensitive once-per-record whole-word {term} search, which year and which month have the highest AFR counts?",
            f"Search AFR for {term} once per record and report the total, the peak year and the peak month.",
        ])
        example = build(question, [("query_data", args)], gold)
        if example:
            yield example

        for year in YEARS:
            year_args = {"dataset": "afr", "metric": "count", "pattern": pattern, "year": year}
            year_result = run_tool("query_data", year_args)
            if not year_result.ok:
                continue
            count = _values(year_result)["match_count"]
            gold_year = f"There are {fmt_int(count)} AFR records matching whole-word {term} in {year}."
            example = build(
                f"How many {year} AFR records mention {term}, counted once per record?",
                [("query_data", year_args)], gold_year,
            )
            if example:
                yield example

    for term in RNG.sample(AFR_TERMS, k=40):
        pattern = term if any(ch in term for ch in "?|") else rf"\b{term}\b"
        year = RNG.choice(YEARS)
        args = {"dataset": "afr", "metric": "share", "pattern": pattern, "year": year}
        result = run_tool("query_data", args)
        if not result.ok:
            continue
        v = _values(result)
        gold = (
            f"{fmt_int(v['match_count'])} of {fmt_int(v['total_records'])} AFR records in {year} "
            f"mention {term}, a share of {v['share_pct']:.2f}%."
        )
        example = build(f"What share of {year} AFR articles mention {term}?",
                        [("query_data", args)], gold)
        if example:
            yield example


# --------------------------------------------------------------------------
# Windowed sweeps - the same metrics over many periods, so the model learns
# to read the window out of the evidence instead of memorising one answer.
# --------------------------------------------------------------------------
def gen_rba_windows() -> Iterator[Example]:
    spans = [(a, b) for a in range(2010, 2026) for b in range(a, min(a + 4, 2027)) if b <= 2026]
    for start_year, end_year in spans:
        window = {"date_from": f"{start_year}-01-01", "date_to": f"{end_year}-12-31"}
        period = f"{start_year}" if start_year == end_year else f"{start_year} to {end_year}"

        args = {"dataset": "rba", "metric": "count_changes", **window}
        result = run_tool("query_data", args)
        v = _values(result)
        if result.ok and v.get("changes"):
            gold = (
                f"Between {start_year} and {end_year} the RBA changed the cash rate "
                f"{fmt_int(v['changes'])} times: {fmt_int(v['increases'])} increases and "
                f"{fmt_int(v['decreases'])} decreases."
            )
            example = build(f"How many RBA rate changes happened in {period}, split by direction?",
                            [("query_data", args)], gold)
            if example:
                yield example

        for metric, word in (("count_increases", "increases"), ("count_decreases", "decreases")):
            directional = {"dataset": "rba", "metric": metric, **window}
            result = run_tool("query_data", directional)
            v = _values(result)
            if not result.ok or not v.get(word):
                continue
            gold = (
                f"There were {fmt_int(v[word])} rate {word} in {period}, totalling "
                f"{fmt_points(v['cumulative_change'])}."
            )
            example = build(f"How many RBA rate {word} occurred in {period}, and what did they total?",
                            [("query_data", directional)], gold)
            if example:
                yield example


def gen_asx_windows() -> Iterator[Example]:
    for ticker in TICKERS:
        args = {"dataset": "asx", "metric": "full_sample_return", "tickers": [ticker]}
        result = run_tool("query_data", args)
        if result.ok and result.detail.get("returns"):
            value = result.detail["returns"][ticker]
            gold = (
                f"{ticker} returned {fmt_pct(value)} across the full 2015-01-02 to 2021-12-30 sample."
            )
            example = build(f"What was {ticker}'s total return over the full sample?",
                            [("query_data", args)], gold)
            if example:
                yield example

    for year in YEARS:
        basket = {"dataset": "asx", "metric": "basket_return", "year": year,
                  "exclude_tickers": ["TAH.AX"]}
        result = run_tool("query_data", basket)
        v = _values(result)
        if result.ok and "basket_return" in v:
            verb = "rose" if v["basket_return"] >= 0 else "fell"
            gold = f"The non-Tabcorp ASX basket {verb} {fmt_pct(v['basket_return'])} in {year}."
            example = build(f"What was the non-Tabcorp ASX basket's simple average return in {year}?",
                            [("query_data", basket)], gold)
            if example:
                yield example

        volume = {"dataset": "asx", "metric": "avg_volume", "year": year,
                  "exclude_tickers": ["TAH.AX"]}
        result = run_tool("query_data", volume)
        if result.ok and result.detail.get("average_volume"):
            ticker, value = next(iter(result.detail["average_volume"].items()))
            gold = (
                f"{ticker} had the highest average daily volume in {year} at {value:,.2f} shares "
                f"per trading day."
            )
            example = build(f"Excluding Tabcorp, which ticker traded the most shares per day in {year}?",
                            [("query_data", volume)], gold)
            if example:
                yield example

        drawdown = {"dataset": "asx", "metric": "max_drawdown", "year": year,
                    "exclude_tickers": ["TAH.AX"], "top_n": 3}
        result = run_tool("query_data", drawdown)
        if result.ok and result.detail.get("drawdowns"):
            rows = result.detail["drawdowns"][:3]
            gold = "; ".join(
                f"{i}) {r['ticker']} {fmt_pct(r['drawdown_pct'])}, {r['peak_date']} to {r['trough_date']}"
                for i, r in enumerate(rows, start=1)
            ) + "."
            example = build(f"Rank the three worst non-Tabcorp drawdowns during {year} with their peak and trough dates.",
                            [("query_data", drawdown)], gold)
            if example:
                yield example

    # Randomised event windows: teaches exact-date close-to-close reading.
    for _ in range(220):
        start = date(RNG.choice(YEARS), RNG.randint(1, 12), RNG.randint(1, 28))
        end = start + timedelta(days=RNG.choice([7, 14, 30, 90]))
        if end > date(2021, 12, 30):
            continue
        args = {"dataset": "asx", "metric": "basket_return", "date_from": start.isoformat(),
                "date_to": end.isoformat(), "exclude_tickers": ["TAH.AX"]}
        result = run_tool("query_data", args)
        v = _values(result)
        if not result.ok or "basket_return" not in v:
            continue
        verb = "rose" if v["basket_return"] >= 0 else "fell"
        gold = (
            f"The non-Tabcorp basket {verb} {fmt_pct(v['basket_return'])} between "
            f"{start.isoformat()} and {end.isoformat()}."
        )
        example = build(
            f"What was the non-Tabcorp basket return from {start.isoformat()} to {end.isoformat()}?",
            [("query_data", args)], gold,
        )
        if example:
            yield example


