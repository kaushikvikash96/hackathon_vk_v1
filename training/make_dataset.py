def gen_limitations() -> Iterator[Example]:
    coverage = [("query_data", {"dataset": "cross", "metric": "coverage"})]

    unsupported = [
        ("Can the three supplied datasets support a fully observed analysis of how AFR news and ASX prices reacted to the 2022-2023 RBA tightening cycle?",
         "No. The RBA data covers the 13 hikes from 2022-05-04 to 2023-11-08, but both the AFR and "
         "ASX datasets end in 2021. A three-dataset reaction analysis is therefore unsupported by "
         "the supplied evidence."),
        ("How did ASX share prices respond to the 2024 RBA decisions?",
         "This cannot be answered from the supplied data. The ASX dataset ends on 2021-12-30, so "
         "there are no 2024 prices to compare against the 2024 RBA decisions."),
        ("What did the AFR write about the cash rate during 2023?",
         "This cannot be answered from the supplied data. The AFR corpus ends in December 2021, so "
         "it contains no 2023 articles."),
        ("Summarise ASX trading volumes during 2022.",
         "This cannot be answered from the supplied data. The ASX dataset covers 2015-01-02 to "
         "2021-12-30 and contains no 2022 sessions."),
        ("Compare AFR coverage of interest rates in 2022 with the RBA decisions that year.",
         "Only half of this comparison is possible. The RBA dataset covers 2022, but the AFR corpus "
         "ends in December 2021, so there is no 2022 news coverage to compare against."),
    ]
    for question, gold in unsupported:
        for _ in range(10):  # repeated so the behaviour is learned, not memorised as one string
            example = build(question, coverage, gold)
            if example:
                yield example

    for _ in range(90):
        year = RNG.choice([2022, 2023, 2024, 2025])
        ticker = RNG.choice(TICKERS)
        gold = (
            f"This cannot be answered from the supplied data. The ASX dataset ends on 2021-12-30, "
            f"so {ticker} has no {year} price history in the supplied evidence."
        )
        example = build(f"What was {ticker}'s return in {year}?", coverage, gold)
        if example:
            yield example


