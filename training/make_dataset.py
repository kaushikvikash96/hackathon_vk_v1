Example = dict[str, Any]


def build(question: str, calls: list[tuple[str, dict]], gold: str) -> Example | None:
    """Run the tools for real, then pair their evidence with the computed answer."""
    results: list[ToolResult] = []
    for tool_name, args in calls:
        result = run_tool(tool_name, args)
        if not result.ok:
            return None
        results.append(result)
    if not results:
        return None
    return {
        "question": question,
        "evidence": render_evidence(results),
        "answer": gold,
        "tools": [f"{c[1].get('dataset', c[0])}.{c[1].get('metric', '')}".strip(".") for c in calls],
    }


def _values(result: ToolResult) -> dict[str, Any]:
    return {f.label: f.value for f in result.facts}


def _query(dataset: str, metric: str, **args: Any) -> ToolResult:
    return run_tool("query_data", {"dataset": dataset, "metric": metric, **args})


