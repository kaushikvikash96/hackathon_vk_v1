# Sentiment (labels produced separately by label_sentiment.py)
# --------------------------------------------------------------------------
def gen_sentiment(labels_path: Path) -> Iterator[Example]:
    if not labels_path.exists():
        print(f"note: {labels_path} not found - skipping sentiment examples. "
              f"Run training/label_sentiment.py on the cluster first.", file=sys.stderr)
        return

    with open(labels_path, encoding="utf-8") as handle:
        for line in handle:
            line = line.strip()
            if not line:
                continue
            row = json.loads(line)
            headline, published = row["headline"], row["publication_date"]
            gold = (
                f"The RBA cash-rate target in force was {row['rate']}. The article's sentiment is "
                f"{row['sentiment']}. The likely direction for {row['scope']} is {row['direction']}."
            )
            example = build(
                f'Retrieve the AFR article "{headline}" published {published} and use the RBA '
                f"cash-rate target in force on that date. Classify the article's financial-market "
                f"sentiment as positive, negative, or mixed; state the likely direction for "
                f"{row['scope']}.",
                [("retrieve", {"headline": headline, "date": published}),
                 ("query_data", {"dataset": "rba", "metric": "lookup_rate", "date": published})],
                gold,
            )
            if example:
                yield example


