def gen_asx() -> Iterator[Example]:
    for year in YEARS:
        args = {"dataset": "asx", "metric": "rank_annual_returns", "year": year,
                "exclude_tickers": ["TAH.AX"]}
        result = run_tool("query_data", args)
        if not result.ok:
            continue
        ranking = result.detail["ranking"]
        gold = (
            f"{ranking[0]['ticker']} was best at {fmt_pct(ranking[0]['return_pct'])}; "
            f"{ranking[-1]['ticker']} was worst at {fmt_pct(ranking[-1]['return_pct'])}."
        )
        for phrasing in (
            f"Excluding Tabcorp, which ticker had the best and worst {year} return?",
            f"In {year}, which non-Tabcorp stock gained the most and which lost the most?",
        ):
            example = build(phrasing, [("query_data", args)], gold)
            if example:
                yield example

        top3 = ranking[:3]
        gold_rank = "; ".join(
            f"{i}) {row['ticker']} {fmt_pct(row['return_pct'])}" for i, row in enumerate(top3, start=1)
        ) + "."
        example = build(
            f"Rank the top three non-Tabcorp performers in {year} with their returns.",
            [("query_data", {**args, "top_n": 3})], gold_rank,
        )
        if example:
            yield example

    for ticker in TICKERS:
        for year in YEARS:
            args = {"dataset": "asx", "metric": "annual_return", "year": year, "tickers": [ticker]}
            result = run_tool("query_data", args)
            if not result.ok or not result.detail.get("returns"):
                continue
            value = result.detail["returns"][ticker]
            gold = f"{ticker} returned {fmt_pct(value)} in {year}, measured first close to last close."
            question = RNG.choice([
                f"What was {ticker}'s {year} return?",
                f"How did {ticker} perform over {year}?",
                f"Give {ticker}'s first-to-last close return for {year}.",
            ])
            example = build(question, [("query_data", args)], gold)
            if example:
                yield example

    # Event windows around every RBA change inside the ASX coverage period.
    changes = [d for d in data_rba.load() if d.change != 0 and date(2015, 1, 5) <= d.effective <= date(2021, 12, 20)]
    for decision in changes:
        end = decision.effective + timedelta(days=7)
        args = {"dataset": "asx", "metric": "basket_return",
                "date_from": decision.effective.isoformat(), "date_to": end.isoformat(),
                "exclude_tickers": ["TAH.AX"]}
        result = run_tool("query_data", args)
        if not result.ok:
            continue
        v = _values(result)
        verb = "rose" if v["basket_return"] >= 0 else "fell"
        gold = (
            f"The non-Tabcorp basket {verb} {fmt_pct(v['basket_return'])} from "
            f"{decision.effective.isoformat()} to {end.isoformat()}, following the RBA move to "
            f"{fmt_rate(decision.target)}."
        )
        example = build(
            f"After the {decision.effective.isoformat()} RBA decision, what was the non-Tabcorp "
            f"basket's one-week return?",
            [("query_data", args),
             ("query_data", {"dataset": "rba", "metric": "lookup_rate",
                             "date": decision.effective.isoformat()})],
            gold,
        )
        if example:
            yield example

    for top_n in (3, 5):
        args = {"dataset": "asx", "metric": "max_drawdown", "exclude_tickers": ["TAH.AX"], "top_n": top_n}
        result = run_tool("query_data", args)
        rows = result.detail["drawdowns"][:top_n]
        gold = "; ".join(
            f"{i}) {r['ticker']} {fmt_pct(r['drawdown_pct'])}, {r['peak_date']} to {r['trough_date']}"
            for i, r in enumerate(rows, start=1)
        ) + "."
        example = build(
            f"Rank the {top_n} worst non-Tabcorp full-sample maximum drawdowns and identify each peak and trough date.",
            [("query_data", args)], gold,
        )
        if example:
            yield example

    args = {"dataset": "asx", "metric": "avg_volume", "exclude_tickers": ["TAH.AX"]}
    result = run_tool("query_data", args)
    ranked = list(result.detail["average_volume"].items())
    gold = (
        f"{ranked[0][0]} has the highest average daily volume at {ranked[0][1]:,.2f} shares "
        f"per trading day."
    )
    for phrasing in (
        "Excluding Tabcorp, which ticker has the highest average daily volume over the full sample?",
        "Which non-Tabcorp stock trades the most shares per day on average?",
    ):
        example = build(phrasing, [("query_data", args)], gold)
        if example:
            yield example

    result = run_tool("query_data", {"dataset": "asx", "metric": "coverage"})
    v = _values(result)
    gold = (
        f"There are {v['ticker_count']} ticker files, each containing "
        f"{fmt_int(v['rows_per_ticker'])} rows, covering {v['first_date']} through {v['last_date']}."
    )
    for phrasing in (
        "What are the dimensions and common date range of the ASX dataset?",
        "How many ASX tickers are supplied, how many rows each, and over what period?",
    ):
        example = build(phrasing, [("query_data", {"dataset": "asx", "metric": "coverage"})], gold)
        if example:
            yield example

    for _ in range(150):
        a, b = RNG.sample(TICKERS, 2)
        year = RNG.choice(YEARS)
        args = {"dataset": "asx", "metric": "correlation", "tickers": [a, b], "year": year}
        result = run_tool("query_data", args)
        if not result.ok:
            continue
        v = _values(result)
        gold = f"The daily-return correlation between {a} and {b} in {year} was {v['correlation']:.3f}."
        example = build(f"How correlated were {a} and {b} during {year}?", [("query_data", args)], gold)
        if example:
            yield example

    for _ in range(150):
        ticker = RNG.choice(TICKERS)
        year = RNG.choice(YEARS)
        args = {"dataset": "asx", "metric": "volatility", "tickers": [ticker], "year": year}
        result = run_tool("query_data", args)
        if not result.ok or not result.facts:
            continue
        value = result.detail["volatility_pct"][ticker]
        gold = f"{ticker}'s annualised volatility in {year} was {value:.2f}%."
        example = build(f"What was {ticker}'s annualised volatility in {year}?",
                        [("query_data", args)], gold)
        if example:
            yield example


