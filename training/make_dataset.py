def to_chat(example: Example) -> dict:
    return {
        "messages": [
            {"role": "system", "content": SYNTH_SYSTEM},
            {"role": "user", "content": SYNTH_USER.format(
                question=example["question"], evidence=example["evidence"])},
            {"role": "assistant", "content": example["answer"]},
        ]
    }


def to_nemo(example: Example) -> dict:
    return {
        "system": SYNTH_SYSTEM,
        "input": SYNTH_USER.format(question=example["question"], evidence=example["evidence"]),
        "output": example["answer"],
    }


def stratified_subset(rows: list[Example], size: int) -> list[Example]:
    """A smaller training set that still contains every question shape.

    Used by the quick fine-tuning profile. Proportional sampling alone would
    drop the rare slices - robustness has only 18 examples - so each source
    gets a floor first and the remainder is filled proportionally. A quick run
    that never sees a limitation case would learn to invent an answer instead
    of stating the limitation.
    """
    by_source: dict[str, list[Example]] = {}
    for row in rows:
        by_source.setdefault(row.get("source", "other"), []).append(row)

    floor = max(1, size // (len(by_source) * 3))
    picked: list[Example] = []
    for source, group in by_source.items():
        take = min(len(group), floor)
        picked.extend(RNG.sample(group, k=take))

    remaining = [r for r in rows if r not in picked]
    shortfall = max(0, size - len(picked))
    if shortfall and remaining:
        picked.extend(RNG.sample(remaining, k=min(shortfall, len(remaining))))

    RNG.shuffle(picked)
    return picked[:size]


def write_split(rows: list[Example], out_dir: Path, name: str) -> None:
    chat_path = out_dir / f"{name}.jsonl"
    nemo_path = out_dir / f"{name}_nemo.jsonl"
    with open(chat_path, "w", encoding="utf-8") as chat, open(nemo_path, "w", encoding="utf-8") as nemo:
        for row in rows:
            chat.write(json.dumps(to_chat(row), ensure_ascii=False) + "\n")
            nemo.write(json.dumps(to_nemo(row), ensure_ascii=False) + "\n")
    print(f"  {name:<6} {len(rows):>5} examples -> {chat_path.name}, {nemo_path.name}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default="training/data")
    parser.add_argument("--sentiment-labels", default="training/data/sentiment_labels.jsonl")
    parser.add_argument("--max-chars", type=int, default=7000,
                        help="Drop examples whose prompt exceeds this (seq len 512 on one node).")
    parser.add_argument("--quick-size", type=int, default=600,
                        help="Size of the stratified subset used by the quick training profile.")
    args = parser.parse_args()

    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)

    generators: list[tuple[str, Callable[[], Iterator[Example]]]] = [
        ("rba", gen_rba),
        ("rba_windows", gen_rba_windows),
        ("asx", gen_asx),
        ("asx_windows", gen_asx_windows),
        ("afr", gen_afr),
        ("limitation", gen_limitations),
        ("robustness", gen_robustness),
        ("sentiment", lambda: gen_sentiment(Path(args.sentiment_labels))),
    ]

    examples: list[Example] = []
    counts: dict[str, int] = {}
    for name, generator in generators:
        produced = [e for e in generator() if e and len(e["evidence"]) <= args.max_chars]
        counts[name] = len(produced)
        for example in produced:
            example["source"] = name
        examples.extend(produced)
        print(f"generated {len(produced):>5} {name} examples")

    RNG.shuffle(examples)
    total = len(examples)
    train_end = int(total * 0.85)
    val_end = int(total * 0.95)

    train_rows = examples[:train_end]
    print(f"\ntotal {total} examples")
    write_split(train_rows, out_dir, "train")
    write_split(examples[train_end:val_end], out_dir, "val")
    write_split(examples[val_end:], out_dir, "test")

    quick_rows = stratified_subset(train_rows, args.quick_size)
    write_split(quick_rows, out_dir, "train_quick")
    quick_mix = {}
    for row in quick_rows:
        quick_mix[row.get("source", "other")] = quick_mix.get(row.get("source", "other"), 0) + 1
    print(f"         quick mix: {quick_mix}")

    (out_dir / "dataset_card.json").write_text(json.dumps({
        "total": total,
        "by_source": counts,
        "splits": {"train": train_end, "val": val_end - train_end, "test": total - val_end,
                   "train_quick": len(quick_rows)},
        "quick_subset": {"size": len(quick_rows), "by_source": quick_mix,
                         "note": "stratified so every question shape survives a short run"},
        "seed": 20260731,
        "format": "system/user/assistant chat plus a NeMo input/output mirror",
        "label_provenance": "computed by the agent's own deterministic tool layer",
        "excludes": "the 15 public calibration questions are held out entirely",
    }, indent=2), encoding="utf-8")
    print(f"\ndataset card -> {out_dir / 'dataset_card.json'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
