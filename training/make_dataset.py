# Robustness: noisy and irrelevant evidence
# --------------------------------------------------------------------------
def gen_robustness() -> Iterator[Example]:
    """Extra unrelated evidence must not change the stated facts."""
    distractors = [
        ("query_data", {"dataset": "asx", "metric": "coverage"}),
        ("query_data", {"dataset": "afr", "metric": "coverage"}),
        ("query_data", {"dataset": "rba", "metric": "coverage"}),
    ]
    base_cases = [
        ("How many RBA decisions changed the cash rate?",
         [("query_data", {"dataset": "rba", "metric": "count_changes"})]),
        ("What was the longest RBA hold streak?",
         [("query_data", {"dataset": "rba", "metric": "max_hold_streak"})]),
        ("Excluding Tabcorp, which stock had the deepest drawdown?",
         [("query_data", {"dataset": "asx", "metric": "max_drawdown",
                          "exclude_tickers": ["TAH.AX"], "top_n": 1})]),
    ]
    golds = {
        "How many RBA decisions changed the cash rate?": None,
        "What was the longest RBA hold streak?": None,
        "Excluding Tabcorp, which stock had the deepest drawdown?": None,
    }

    for question, calls in base_cases:
        primary = run_tool(*calls[0])
        v = _values(primary)
        if question.startswith("How many RBA"):
            golds[question] = (
                f"{fmt_int(v['changes'])} RBA decisions changed the cash rate: "
                f"{fmt_int(v['increases'])} increases and {fmt_int(v['decreases'])} decreases."
            )
        elif question.startswith("What was the longest"):
            golds[question] = (
                f"The longest RBA hold streak ran {fmt_int(v['days'])} days from {v['start_date']} "
                f"to {v['end_date']}, with the rate held at {v['rate_during_hold']}."
            )
        else:
            row = primary.detail["drawdowns"][0]
            golds[question] = (
                f"{row['ticker']} had the deepest non-Tabcorp drawdown at "
                f"{fmt_pct(row['drawdown_pct'])}, from {row['peak_date']} to {row['trough_date']}."
            )

    for question, calls in base_cases:
        for extra in distractors:
            for ordering in ([*calls, extra], [extra, *calls]):
                example = build(question, ordering, golds[question])
                if example:
                    yield example


