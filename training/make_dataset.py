def gen_rba() -> Iterator[Example]:
    decisions = data_rba.load()

    for phrasing in (
        "From the first RBA record to the last, how many cash-rate decisions changed the rate, and how many were increases versus decreases?",
        "How many RBA decisions actually moved the cash rate, split into rises and falls?",
        "Across the whole RBA file, count the rate changes and break them into increases and decreases.",
    ):
        result = _query("rba", "count_changes")
        v = _values(result)
        gold = (
            f"{fmt_int(v['changes'])} of the {fmt_int(len(decisions))} decision records changed "
            f"the rate: {fmt_int(v['increases'])} increases and {fmt_int(v['decreases'])} decreases."
        )
        example = build(phrasing, [("query_data", {"dataset": "rba", "metric": "count_changes"})], gold)
        if example:
            yield example

    for phrasing in (
        "What is the lowest cash-rate target in the RBA dataset, when did it first take effect, and how many decision records show that rate?",
        "Give the minimum cash-rate target, its first effective date, and the number of records at that level.",
    ):
        result = _query("rba", "extremes")
        v = _values(result)
        gold = (
            f"The lowest cash-rate target in the RBA dataset was {v['lowest_target']}, which first "
            f"took effect on {v['lowest_first_date']}, and {fmt_int(v['lowest_record_count'])} "
            f"decision records show that rate."
        )
        example = build(phrasing, [("query_data", {"dataset": "rba", "metric": "extremes"})], gold)
        if example:
            yield example

    result = _query("rba", "extremes")
    v = _values(result)
    gold = (
        f"The highest cash-rate target in the RBA dataset was {v['highest_target']}, first effective "
        f"on {v['highest_first_date']}, appearing across {fmt_int(v['highest_record_count'])} "
        f"decision records."
    )
    example = build(
        "What is the highest cash-rate target ever in the RBA dataset, and how many records show it?",
        [("query_data", {"dataset": "rba", "metric": "extremes"})], gold,
    )
    if example:
        yield example

    for phrasing in (
        "What was the longest period the RBA held rates unchanged?",
        "What was the longest stretch between two non-zero RBA rate changes?",
        "How long was the RBA's longest pause between rate moves, and what were the rates either side?",
    ):
        result = _query("rba", "max_hold_streak")
        v = _values(result)
        gold = (
            f"The longest stretch between two non-zero RBA rate changes was {fmt_int(v['days'])} days, "
            f"lasting from {v['start_date']} to {v['end_date']}, during which the rate held at "
            f"{v['rate_during_hold']} before changing to {v['rate_after']}."
        )
        example = build(phrasing, [("query_data", {"dataset": "rba", "metric": "max_hold_streak"})], gold)
        if example:
            yield example

    # Rate in force on a date - the on-or-before rule.
    sampled = [RNG.randrange(len(decisions)) for _ in range(420)]
    for i in sampled:
        target_day = decisions[i].effective + timedelta(days=RNG.randint(0, 25))
        if target_day > decisions[-1].effective:
            continue
        result = _query("rba", "lookup_rate", date=target_day.isoformat())
        if not result.ok:
            continue
        v = _values(result)
        gold = (
            f"The RBA cash-rate target in force on {target_day.isoformat()} was "
            f"{fmt_rate(v['target'])}, set by the decision effective {v['effective_date']}."
        )
        question = RNG.choice([
            f"What was the RBA cash-rate target in force on {target_day.isoformat()}?",
            f"Which cash rate applied on {target_day.isoformat()}, and which decision set it?",
            f"State the RBA cash-rate target that applied on {target_day.isoformat()}.",
        ])
        example = build(question, [("query_data", {"dataset": "rba", "metric": "lookup_rate",
                                                   "date": target_day.isoformat()})], gold)
        if example:
            yield example

    # Cycles over many windows.
    windows = [(a, b) for a in range(2010, 2026) for b in (a, a + 1, a + 2, a + 3) if b <= 2026]
    for start_year, end_year in windows:
        direction = RNG.choice(["cuts", "hikes"])
        args = {
            "dataset": "rba", "metric": "cycle_summary", "direction": direction,
            "date_from": f"{start_year}-01-01", "date_to": f"{end_year}-12-31",
        }
        result = run_tool("query_data", args)
        v = _values(result)
        if not result.ok or not v.get("count"):
            continue
        word = "cuts" if direction == "cuts" else "hikes"
        gold = (
            f"There were {fmt_int(v['count'])} {word} between {v['first_date']} and {v['last_date']}, "
            f"totalling {fmt_points(v['cumulative_change'])}. The target went from "
            f"{fmt_rate(v['target_before'])} before the first move to {fmt_rate(v['target_after'])} "
            f"at the end of the period."
        )
        period = f"{start_year}" if start_year == end_year else f"{start_year}-{end_year}"
        question = RNG.choice([
            f"Across the {period} period, how many {word} occurred and how far did the target move?",
            f"Summarise the RBA {word} between {start_year} and {end_year}, including the cumulative change.",
            f"How many {word} did the RBA make in {period}, and what were the start and end targets?",
        ])
        example = build(question, [("query_data", args)], gold)
        if example:
            yield example


