"""Build the Nemotron synthesis fine-tuning set.

    python training/make_dataset.py --out training/data

Every example is generated by running the *real* tool layer and rendering a
reference-style answer from the values it returns. Gold answers are therefore
computed, never model-written, so no label can contain a hallucinated number.

Each example is exactly the prompt the agent sends at inference time:

    system : prompts.SYNTH_SYSTEM   (including "detailed thinking off")
    user   : QUESTION + EVIDENCE json
    output : a 1-3 sentence answer stating every requested component

Composition (~2,800 examples):
    RBA / ASX / AFR / cross metrics ....... computed question-answer pairs
    limitation cases ...................... evidence cannot support the question
    robustness cases ...................... paraphrases and noisy evidence
    sentiment cases ....................... AFR article + rate, labels from
                                            training/data/sentiment_labels.jsonl
                                            (see label_sentiment.py)

The 15 public calibration questions are never used as training data.
"""

